    await page.waitForFunction(() => document.querySelector('#notificationButton').textContent.includes('(1)'));
    await page.locator('#notificationButton').click();
    await page.locator('#notificationList button').first().click();
    await page.locator('[data-editor-tab=conversation]').click();
    await page.locator('[data-reply]').first().click();
    await page.locator('#commentText').fill('Validação concluída. Evidências anexadas.');
    await page.locator('#sendComment').click();
    await page.waitForFunction(() => document.querySelectorAll('.card-comment').length === 2 && !collaborationBusy);
    assert.match(await page.locator('.card-comment').last().innerText(), /Bruno teste/);
    assert.equal(await page.locator('.card-comment blockquote').count(), 1);
    await page.locator('[data-editor-tab=evidence]').click();
    await page.locator('#evidenceDropZone').evaluate(zone => {
      const data = new DataTransfer();
      const bytes = Uint8Array.from(atob('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII='), c => c.charCodeAt(0));
      data.items.add(new File([bytes], 'captura.png', { type: 'image/png' }));
      zone.dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }));
      const dropped = new DataTransfer();
      dropped.items.add(new File(['evidencia\r\n--'], 'arquivo.bin', { type: 'application/octet-stream' }));
      zone.dispatchEvent(new DragEvent('drop', { dataTransfer: dropped, bubbles: true, cancelable: true }));
    });
