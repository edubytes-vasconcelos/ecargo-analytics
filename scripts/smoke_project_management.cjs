    assert.equal(await page.locator('.evidence-preview').count(), 3);
    await page.locator('[data-remove-evidence]').last().click();
    await page.locator('#sendEvidence').click();
    await page.waitForFunction(() => document.querySelectorAll('.evidence-entry').length === 2 && !collaborationBusy);
    const binaryUrl = await page.locator('.evidence-entry a').filter({ hasText: 'arquivo.bin' }).getAttribute('href');
    const response = await collaboratorContext.request.get(new URL(binaryUrl, base).href);
    assert.equal(response.status(), 200);
    assert.equal((await response.body()).toString(), 'evidencia\r\n--');
    fs.mkdirSync('outputs', { recursive: true });
