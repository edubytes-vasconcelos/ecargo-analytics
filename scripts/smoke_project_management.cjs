    await page.locator('#localPasswordForm').waitFor({ state: 'visible' });
    assert.equal(await page.locator('#closeLocalAuth').isVisible(), false);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#localAuthModal').isVisible(), true);
    await page.locator('#localCurrentPassword').fill(generated);
    await page.locator('#localNewPassword').fill('Bruno-new-password-789');
    await page.locator('#localConfirmPassword').fill('Bruno-new-password-789');
